<#
.SYNOPSIS
    Generates the vanilla block state property names the client is allowed to read.

.DESCRIPTION
    Block state property names are interaction fields: a typo does not fail loudly, it silently
    falls back to whatever the caller does when the lookup misses. That is how the copper golem
    statue rendered every pose as standing until someone noticed. This script reads the names from
    the reference sources so our code can be checked against them instead of trusted from memory.

    Requires the analysis workspace (MC_ANALYSIS_ROOT, default ../mc-26.3-analysis).

.PARAMETER Check
    Verify the checked in file is current instead of rewriting it.
#>
[CmdletBinding()]
param(
    [switch]$Check
)

$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$analysisRoot = if ($env:MC_ANALYSIS_ROOT) { $env:MC_ANALYSIS_ROOT } else { Join-Path (Split-Path -Parent $repoRoot) 'mc-26.3-analysis' }
$sourceRoot = Join-Path $analysisRoot 'src'
$output = Join-Path $repoRoot 'src/Sharpcraft.Common/Registries/VanillaBlockStatePropertyNames.cs'

if (-not (Test-Path $sourceRoot)) {
    throw "Reference sources not found at $sourceRoot. Set MC_ANALYSIS_ROOT to the analysis workspace."
}

$pattern = '(EnumProperty|BooleanProperty|IntegerProperty)\.create\(\s*"([a-z0-9_]+)"'
$names = [System.Collections.Generic.SortedSet[string]]::new([System.StringComparer]::Ordinal)
foreach ($file in Get-ChildItem $sourceRoot -Recurse -Filter '*.java') {
    foreach ($match in (Select-String -Path $file.FullName -Pattern $pattern -AllMatches).Matches) {
        [void]$names.Add($match.Groups[2].Value)
    }
}

if ($names.Count -eq 0) {
    throw 'No property names found; the reference sources may have changed shape.'
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('// SPDX-License-Identifier: LGPL-3.0-or-later')
$lines.Add('// Copyright (C) 2026 Sharpcraft contributors')
$lines.Add('')
$lines.Add('// <auto-generated>')
$lines.Add('// Generated by tools/blocks/generate-block-state-property-names.ps1 from the 26.3 sources.')
$lines.Add('// Property names are interaction fields: a misspelling falls back silently instead of failing,')
$lines.Add('// so every name we read is checked against this table rather than trusted from memory.')
$lines.Add('// </auto-generated>')
$lines.Add('')
$lines.Add('namespace Sharpcraft.Common.Registries;')
$lines.Add('')
$lines.Add('/// <summary>Every block state property name the reference declares.</summary>')
$lines.Add('[Sharpcraft.Common.Reference.ReferenceClass("net.minecraft.world.level.block.state.properties.BlockStateProperties", "ref://mc-26.3-analysis/src/net/minecraft/world/level/block/state/properties/BlockStateProperties.java", Kind = Sharpcraft.Common.Reference.ReferenceKind.Mirror, Status = Sharpcraft.Common.Reference.ReferenceStatus.Partial, Note = "Block state property names; a mismatch makes lookups miss silently")]')
$lines.Add('public static class VanillaBlockStatePropertyNames')
$lines.Add('{')
$lines.Add('    /// <summary>How many names the reference declares.</summary>')
$lines.Add("    public const int Count = $($names.Count);")
$lines.Add('')
$lines.Add('    /// <summary>The names, sorted ordinally so a binary search applies.</summary>')
$lines.Add('    public static IReadOnlyList<string> Names { get; } =')
$lines.Add('    [')
foreach ($name in $names) {
    $lines.Add("        `"$name`",")
}
$lines.Add('    ];')
$lines.Add('')
$lines.Add('    /// <summary>Whether the reference declares a property with this name.</summary>')
$lines.Add('    /// <param name="name">Property name, without a namespace.</param>')
$lines.Add('    /// <returns>True when the name exists.</returns>')
$lines.Add('    public static bool Contains(string name)')
$lines.Add('    {')
$lines.Add('        ArgumentNullException.ThrowIfNull(name);')
$lines.Add('        var low = 0;')
$lines.Add('        var high = Names.Count - 1;')
$lines.Add('        while (low <= high)')
$lines.Add('        {')
$lines.Add('            var middle = (low + high) >> 1;')
$lines.Add('            var order = string.CompareOrdinal(Names[middle], name);')
$lines.Add('            if (order == 0)')
$lines.Add('            {')
$lines.Add('                return true;')
$lines.Add('            }')
$lines.Add('')
$lines.Add('            if (order < 0)')
$lines.Add('            {')
$lines.Add('                low = middle + 1;')
$lines.Add('            }')
$lines.Add('            else')
$lines.Add('            {')
$lines.Add('                high = middle - 1;')
$lines.Add('            }')
$lines.Add('        }')
$lines.Add('')
$lines.Add('        return false;')
$lines.Add('    }')
$lines.Add('}')

$text = ($lines -join [Environment]::NewLine) + [Environment]::NewLine

if ($Check) {
    if (-not (Test-Path $output)) {
        throw "Missing $output; run without -Check to generate it."
    }

    # Git may check the file out with a byte order mark or with platform line endings, so the
    # comparison normalises both sides instead of failing on encoding details.
    function Normalize([string] $value) {
        return ($value -replace "`r`n", "`n").TrimStart([char]0xFEFF).TrimEnd()
    }

    if ((Normalize (Get-Content $output -Raw)) -ne (Normalize $text)) {
        throw 'block state property names are stale; run tools/blocks/generate-block-state-property-names.ps1'
    }

    Write-Output "block state property names: ok ($($names.Count) names)"
    return
}

Set-Content -Path $output -Value $text -Encoding utf8 -NoNewline
Write-Output "block state property names: wrote $($names.Count) names"
