<#
.SYNOPSIS
    Generates the vanilla block occlusion predicates ambient occlusion depends on.

.DESCRIPTION
    The reference asks three different questions about a block state:

      isCollisionShapeFullBlock  -> the 0.2 / 1.0 shade and the faceCubic fallback
      isSolidRender              -> part of isLightPermeable
      getLightDampening          -> the rest of isLightPermeable

    They do not agree, and none of them is "has an opaque texture": glass and ice have a
    full collision shape while their occlusion shape is empty (so the shade is 0.2 and they
    are light permeable), leaves are the same, and a slab is not collision-full but does
    occlude. Guessing from the sprite alpha gets all of those backwards, which is why this
    table is generated from the jar rather than written by hand.

    The input is the probe output of ref://mc-26.3-analysis/vectors/BlockOcclusionVectors.java:

        cd <analysis>/vectors
        .\run-probe.ps1 -Name BlockOcclusionVectors -Args block-occlusion.tsv

    Requires the analysis workspace (MC_ANALYSIS_ROOT, default ../mc-26.3-analysis).

.PARAMETER Check
    Verify the checked in file is current instead of rewriting it.
#>
[CmdletBinding()]
param(
    [switch]$Check
)

$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$analysisRoot = if ($env:MC_ANALYSIS_ROOT) { $env:MC_ANALYSIS_ROOT } else { Join-Path (Split-Path -Parent $repoRoot) 'mc-26.3-analysis' }
$input = Join-Path $analysisRoot 'vectors/block-occlusion.tsv'
$output = Join-Path $repoRoot 'src/Sharpcraft.Common/Registries/VanillaBlockOcclusion.cs'

if (-not (Test-Path $input)) {
    throw "Probe output not found at $input. Run the probe first: run-probe.ps1 -Name BlockOcclusionVectors -Args block-occlusion.tsv"
}

$rows = @()
foreach ($line in (Get-Content $input | Select-Object -Skip 1)) {
    if (-not $line.Trim()) { continue }
    $parts = $line -split "`t"
    if ($parts.Count -lt 5) { throw "Malformed row: $line" }

    $code = 0
    if ($parts[1] -eq 'true') { $code = $code -bor 1 }
    if ($parts[2] -eq 'true') { $code = $code -bor 2 }
    $code = $code -bor ([int]$parts[3] -shl 2)
    $rows += [pscustomobject]@{ Id = $parts[0]; Code = $code }
}

$rows = $rows | Sort-Object -Property Id -CaseSensitive
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('// SPDX-License-Identifier: LGPL-3.0-or-later')
$lines.Add('// Copyright (C) 2026 Sharpcraft contributors')
$lines.Add('')
$lines.Add('// <auto-generated>')
$lines.Add('// Generated by tools/blocks/generate-block-occlusion-table.ps1 from the 26.3 jar probe')
$lines.Add('// (ref://mc-26.3-analysis/vectors/BlockOcclusionVectors.java).')
$lines.Add('// Ambient occlusion asks three different questions per block state and they disagree: glass and ice')
$lines.Add('// have a full collision shape but an empty occlusion shape, a slab occludes without being full.')
$lines.Add('// </auto-generated>')
$lines.Add('')
$lines.Add('namespace Sharpcraft.Common.Registries;')
$lines.Add('')
$lines.Add('/// <summary>What the reference asks about a block before it shades or occludes with it.</summary>')
$lines.Add('/// <param name="CollisionFullBlock">Whether the collision shape is a full block (the 0.2 / 1.0 shade).</param>')
$lines.Add('/// <param name="SolidRender">Whether the occlusion shape is a full block.</param>')
$lines.Add('/// <param name="LightDampening">How much light the block absorbs, zero to fifteen.</param>')
$lines.Add('[Sharpcraft.Common.Reference.ReferenceClass("net.minecraft.world.level.block.state.BlockBehaviour", "ref://mc-26.3-analysis/src/net/minecraft/world/level/block/state/BlockBehaviour.java", Kind = Sharpcraft.Common.Reference.ReferenceKind.Mirror, Status = Sharpcraft.Common.Reference.ReferenceStatus.Partial, Note = "isCollisionShapeFullBlock / isSolidRender / getLightDampening per block")]')
$lines.Add('public readonly record struct BlockOcclusionInfo(bool CollisionFullBlock, bool SolidRender, int LightDampening)')
$lines.Add('{')
$lines.Add('    /// <summary>Whether the block lets light through, which is what the diagonal rule reads.</summary>')
$lines.Add('    /// <remarks>ref BlockBehaviour.java:808-810: permeable when the occlusion shape is not full, or nothing is absorbed.</remarks>')
$lines.Add('    public bool LightPermeable => !SolidRender || LightDampening == 0;')
$lines.Add('}')
$lines.Add('')
$lines.Add('/// <summary>The occlusion predicates of every vanilla block, from the jar probe.</summary>')
$lines.Add('[Sharpcraft.Common.Reference.ReferenceClass("net.minecraft.world.level.block.state.BlockBehaviour", "ref://mc-26.3-analysis/src/net/minecraft/world/level/block/state/BlockBehaviour.java", Kind = Sharpcraft.Common.Reference.ReferenceKind.Mirror, Status = Sharpcraft.Common.Reference.ReferenceStatus.Partial, Note = "Per block isCollisionShapeFullBlock / isSolidRender / getLightDampening for the default state")]')
$lines.Add('public static class VanillaBlockOcclusion')
$lines.Add('{')
$lines.Add("    /// <summary>How many blocks the reference registers.</summary>")
$lines.Add("    public const int Count = $($rows.Count);")
$lines.Add('')
$lines.Add('    /// <summary>Looks a block up, or reports that it is unknown so the caller can fall back visibly.</summary>')
$lines.Add('    /// <param name="block">Block identifier.</param>')
$lines.Add('    /// <param name="info">Predicates the reference reports for the default state.</param>')
$lines.Add('    public static bool TryGet(Sharpcraft.Common.Identifiers.Identifier block, out BlockOcclusionInfo info)')
$lines.Add('    {')
$lines.Add('        if (Table.TryGetValue(block.Path, out var code))')
$lines.Add('        {')
$lines.Add('            info = new BlockOcclusionInfo((code & 1) != 0, (code & 2) != 0, code >> 2);')
$lines.Add('            return true;')
$lines.Add('        }')
$lines.Add('')
$lines.Add('        info = default;')
$lines.Add('        return false;')
$lines.Add('    }')
$lines.Add('')
$lines.Add('    /// <summary>Encoded predicates per block path: bit 0 collision full, bit 1 solid render, bits 2..5 dampening.</summary>')
$lines.Add('    private static readonly Dictionary<string, byte> Table = new(StringComparer.Ordinal)')
$lines.Add('    {')
foreach ($row in $rows) {
    $path = $row.Id -replace '^minecraft:', ''
    $lines.Add("        [`"$path`"] = $($row.Code),")
}
$lines.Add('    };')
$lines.Add('}')

$text = ($lines -join "`n") + "`n"

if ($Check) {
    if (-not (Test-Path $output)) { throw "Missing $output; run without -Check first." }
    $current = (Get-Content $output -Raw) -replace "`r`n", "`n"
    if ($current -ne $text) {
        throw "VanillaBlockOcclusion.cs is stale. Re-run tools/blocks/generate-block-occlusion-table.ps1."
    }

    Write-Output "block occlusion table: ok ($($rows.Count) blocks)"
    return
}

[System.IO.File]::WriteAllText($output, $text)
Write-Output "block occlusion table: wrote $($rows.Count) blocks to $output"
