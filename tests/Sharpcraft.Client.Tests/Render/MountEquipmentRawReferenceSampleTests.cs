/// <summary>
/// B-2 (#228): saddle, llama-decor and happy-ghast-harness equipment layers are authored in the reference
/// source frame. These tests compare the production <c>BuildLayers</c> equipment layer against the jar
/// samples per source key (layer|part|cube|polygon|vertex), position and UV together at 1e-5.
/// </summary>
/// <remarks>
/// Sample layers are model-space raw vertices generated by
/// <c>ref://mc-26.3-analysis/vectors/RawRenderUnitProbe.java</c>; production emits them through the living path
/// with <c>rawSourceFrame: true</c> and baseline 0. The raw bake folds the definition scale into the tree, so
/// the living world is exactly <c>sample * EntityPlaceholderMesher.ModelScale</c> (checked against
/// <c>BuildModel(modelScale: 1)</c>); the test inverts that frame before comparing. Samples that contain
/// several source layers (equine saddles, llama adult/baby) are mapped explicitly by sample layer, never guessed.
/// </remarks>
public sealed class MountEquipmentRawReferenceSampleTests
{
    private const float Tolerance = 1e-5f;
    private const string Saddle = "minecraft:saddle";
    private const string WhiteCarpet = "minecraft:white_carpet";
    private const string WhiteHarness = "minecraft:white_harness";

    // sample file, sample layer, entity type id, baby, equipment slot, item, production layer, part mapping
    public static TheoryData<string, string, int, bool, int, string, string, string> Cases => new()
    {
        { "equine-saddle-raw-vectors.reference.txt", "HORSE_SADDLE", HorseModelDefinition.HorseEntityTypeId, false, 7, Saddle, "equipment_HorseSaddle_7", "default" },
        { "equine-saddle-raw-vectors.reference.txt", "DONKEY_SADDLE", HorseModelDefinition.DonkeyEntityTypeId, false, 7, Saddle, "equipment_DonkeySaddle_7", "default" },
        { "equine-saddle-raw-vectors.reference.txt", "MULE_SADDLE", HorseModelDefinition.MuleEntityTypeId, false, 7, Saddle, "equipment_MuleSaddle_7", "default" },
        { "equine-saddle-raw-vectors.reference.txt", "SKELETON_HORSE_SADDLE", HorseModelDefinition.SkeletonHorseEntityTypeId, false, 7, Saddle, "equipment_SkeletonHorseSaddle_7", "default" },
        { "equine-saddle-raw-vectors.reference.txt", "ZOMBIE_HORSE_SADDLE", HorseModelDefinition.ZombieHorseEntityTypeId, false, 7, Saddle, "equipment_ZombieHorseSaddle_7", "default" },
        { "camel-saddle-raw-vectors.reference.txt", "CAMEL_SADDLE", CamelModelDefinition.CamelEntityTypeId, false, 7, Saddle, "equipment_CamelSaddle_7", "camel-head" },
        { "nautilus-saddle-raw-vectors.reference.txt", "NAUTILUS_SADDLE", NautilusModelDefinition.NautilusEntityTypeId, false, 7, Saddle, "equipment_NautilusSaddle_7", "default" },
        { "llama-decor-raw-vectors.reference.txt", "LLAMA_DECOR", LlamaModelDefinition.LlamaEntityTypeId, false, 6, WhiteCarpet, "equipment_LlamaBody_6", "default" },
        { "llama-decor-raw-vectors.reference.txt", "LLAMA_BABY_DECOR", LlamaModelDefinition.LlamaEntityTypeId, true, 6, WhiteCarpet, "equipment_LlamaBody_6", "baby-llama-head" },
        { "happy-ghast-harness-raw-vectors.reference.txt", "HAPPY_GHAST_HARNESS", HappyGhastModelDefinition.HappyGhastEntityTypeId, false, 6, WhiteHarness, "equipment_HappyGhastBody_6", "default" }
    };

    [Theory]
    [MemberData(nameof(Cases))]
    public void ProductionEquipmentLayerMatchesTheSourceSamplePerKey(string sampleFile, string sampleLayer, int typeId,
        bool baby, int slot, string itemIdentifier, string productionLayer, string mapping)
    {
        var definition = EntityModelResolver.Resolve(typeId, baby);
        var layer = definition.RenderLayers.Single(entry => entry.Name == productionLayer);
        var model = layer.Model!;
        Assert.True(model.RawSourceFrame, $"{productionLayer}: layer model must be rawSourceFrame");
        Assert.Equal(0f, model.BaselinePx);
        Assert.Equal(0f, model.SourceFrameBaselinePx);

        var itemId = EntityModelResolver.Items!.GetId(Identifier.Parse(itemIdentifier));
        Assert.True(itemId >= 0, $"missing item {itemIdentifier}");
        var equipment = slot switch
        {
            6 => new EntityEquipment(-1, -1, -1, -1, -1, -1, itemId, -1),
            7 => new EntityEquipment(-1, -1, -1, -1, -1, -1, -1, itemId),
            _ => throw new Xunit.Sdk.XunitException($"unsupported equipment slot {slot}")
        };
        // yaw 180 makes the entity yaw component identity; IsVehicle makes the saddle lines/reins visible and
        // HasChest the donkey/mule/llama chest boxes, matching the jar probe that baked the whole layer.
        var chested = typeId is HorseModelDefinition.DonkeyEntityTypeId or HorseModelDefinition.MuleEntityTypeId
            or LlamaModelDefinition.LlamaEntityTypeId;
        var state = new EntityRenderState(1, typeId, 0f, 0f, 0f, 180f, 0f, Equipment: equipment, IsVehicle: true,
            IsBaby: baby, HasChest: chested);
        var texturePath = model.TextureSelector?.Invoke(state) ?? model.TexturePath ?? layer.TexturePath;
        Assert.False(string.IsNullOrEmpty(texturePath), $"{productionLayer}: no resolvable texture");
        var atlas = ItemAtlas.FromTextures(new Dictionary<string, TextureData>(StringComparer.Ordinal)
        {
            [texturePath!] = new(model.TextureWidth, model.TextureHeight, new byte[model.TextureWidth * model.TextureHeight * 4])
        });

        var rows = Load(sampleFile).Where(row => row.Layer == sampleLayer).ToArray();
        Assert.NotEmpty(rows);
        // The llama decor sample deliberately contains out-of-range source UVs (u = 1.046875); they must
        // survive unchanged. The per-key comparison below proves the production values.
        if (sampleFile.StartsWith("llama-decor", StringComparison.Ordinal))
        {
            Assert.Contains(Load(sampleFile), row => row.U > 1f);
        }

        var full = BuildLayer(state, model, atlas, onlyPart: null);
        Assert.True(rows.Length == VertexCount(full),
            $"{productionLayer}: full layer vertices {VertexCount(full)} != sample rows {rows.Length}");

        // Map every sample (part, cube) to the unique compiled cube that owns it, mesh that cube in isolation
        // through the real living path, and compare polygon/vertex in raw emit order - position and UV of the
        // same key together. Each production cube may be consumed once, so two sample keys cannot share one
        // production cube and a dropped/extra cube is caught by the consumed count.
        var nodes = Flatten(model.Compiled!.Root).GroupBy(node => node.Name, StringComparer.Ordinal)
            .ToDictionary(group => group.Key, group => group.First(), StringComparer.Ordinal);
        var usedCubes = new HashSet<string>(StringComparer.Ordinal);
        var consumed = 0;
        foreach (var group in rows.GroupBy(row => (row.Part, row.Cube)))
        {
            var nodeName = NodeFor(mapping, group.Key.Part, group.Key.Cube);
            var nodeCube = NodeCubeFor(mapping, group.Key.Part, group.Key.Cube);
            Assert.True(nodes.TryGetValue(nodeName, out var node), $"{productionLayer}: no compiled node '{nodeName}' for {group.Key.Part}");
            Assert.InRange(nodeCube, 0, node!.Cubes.Count - 1);
            var cubeName = node.Cubes[nodeCube].Name;
            Assert.True(usedCubes.Add(cubeName), $"{productionLayer}: sample keys map to the same production cube '{cubeName}'");

            var ordered = group.OrderBy(row => row.Polygon).ThenBy(row => row.Vertex).ToArray();
            var geometry = BuildLayer(state, model, atlas, onlyPart: cubeName);
            Assert.True(ordered.Length == VertexCount(geometry),
                $"{productionLayer}/{cubeName}: cube vertices {VertexCount(geometry)} != sample rows {ordered.Length}");
            for (var i = 0; i < ordered.Length; i++)
            {
                var row = ordered[i];
                var raw = VertexFieldReader.Position(geometry.Vertices, i);
                var actual = new Vector3(-raw.X / EntityPlaceholderMesher.ModelScale, -raw.Y / EntityPlaceholderMesher.ModelScale,
                    raw.Z / EntityPlaceholderMesher.ModelScale);
                Assert.True((actual - row.Position).Length() <= Tolerance,
                    $"{sampleLayer}/{row.Part}#{row.Cube} {row.Key}: position expected {row.Position}, actual {actual}");

                var uv = VertexFieldReader.Uv(geometry.Vertices, i);
                var expectedU = QuantizeHalf(row.U);
                var expectedV = QuantizeHalf(row.V);
                Assert.True(MathF.Abs(uv.U - expectedU) <= Tolerance && MathF.Abs(uv.V - expectedV) <= Tolerance,
                    $"{sampleLayer}/{row.Part}#{row.Cube} {row.Key}: UV expected ({expectedU:F6},{expectedV:F6}), actual ({uv.U:F6},{uv.V:F6})");
            }

            consumed += ordered.Length;
        }

        Assert.Equal(rows.Length, consumed);
    }

    [Theory]
    [InlineData(HorseModelDefinition.HorseEntityTypeId)]
    [InlineData(HorseModelDefinition.DonkeyEntityTypeId)]
    [InlineData(HorseModelDefinition.MuleEntityTypeId)]
    [InlineData(HorseModelDefinition.SkeletonHorseEntityTypeId)]
    [InlineData(HorseModelDefinition.ZombieHorseEntityTypeId)]
    [InlineData(CamelModelDefinition.CamelEntityTypeId)]
    [InlineData(NautilusModelDefinition.NautilusEntityTypeId)]
    [InlineData(LlamaModelDefinition.LlamaEntityTypeId)]
    [InlineData(HappyGhastModelDefinition.HappyGhastEntityTypeId)]
    public void EntitiesWithoutEquipmentEmitNoEquipmentLayer(int typeId)
    {
        var state = new EntityRenderState(1, typeId, 0f, 0f, 0f, 180f, 0f);
        var atlas = ItemAtlas.FromTextures(new Dictionary<string, TextureData>(StringComparer.Ordinal)
        {
            ["probe/none"] = new(64, 64, new byte[64 * 64 * 4])
        });
        var layers = new EntityModelMesher().BuildLayers([state], new SpriteRect(0, 0, 64, 64, 1), 64, 64,
            skinAtlas: atlas, variants: EntityVariantTable.Builtin, pose: new EntityPose());
        Assert.DoesNotContain(layers, layer => layer.Name.StartsWith("equipment_", StringComparison.Ordinal));
    }

    [Fact]
    public void LlamaAdultAndBabyDecorUseDistinctRawTrees()
    {
        var adult = EntityModelResolver.Resolve(LlamaModelDefinition.LlamaEntityTypeId)
            .RenderLayers.Single(layer => layer.Name == "equipment_LlamaBody_6").Model!;
        var baby = EntityModelResolver.Resolve(LlamaModelDefinition.LlamaEntityTypeId, baby: true)
            .RenderLayers.Single(layer => layer.Name == "equipment_LlamaBody_6").Model!;

        Assert.True(adult.RawSourceFrame);
        Assert.True(baby.RawSourceFrame);
        Assert.Equal(0f, adult.BaselinePx);
        Assert.Equal(0f, baby.BaselinePx);
        // Adult decor is the adult llama mesh with grow 0.5 (128x64 texture); baby decor is the baby llama
        // mesh with grow 0.2 (64x64 texture). They must not share the compiled tree.
        Assert.Equal(128, adult.TextureWidth);
        Assert.Equal(64, adult.TextureHeight);
        Assert.Equal(64, baby.TextureWidth);
        Assert.Equal(64, baby.TextureHeight);
        Assert.NotSame(adult.Compiled, baby.Compiled);
        Assert.NotEmpty(adult.Compiled!.Cubes);
    }

    private static DynamicGeometry BuildLayer(EntityRenderState state, EntityModelDefinition model, ItemAtlas atlas, string? onlyPart)
    {
        var layers = new EntityModelMesher().BuildLayers([state], new SpriteRect(0, 0, model.TextureWidth, model.TextureHeight, 1),
            model.TextureWidth, model.TextureHeight, onlyPart: onlyPart, skinAtlas: atlas,
            variants: EntityVariantTable.Builtin, pose: new EntityPose());
        return layers.Single(layer => layer.Name == model.Name).Geometry;
    }

    private static string NodeFor(string mapping, string partPath, int cube) => mapping switch
    {
        "camel-head" when partPath == "/body/head" => new[] { "head_lower", "head_upper", "head_snout" }[cube],
        "baby-llama-head" when partPath == "/head" => new[] { "head", "snout", "ear_right", "ear_left" }[cube],
        _ => partPath.Split('/').Last()
    };

    private static int NodeCubeFor(string mapping, string partPath, int cube) => mapping switch
    {
        "camel-head" when partPath == "/body/head" => 0,
        "baby-llama-head" when partPath == "/head" => 0,
        _ => cube
    };

    private static IEnumerable<EntityModelPartNode> Flatten(EntityModelPartNode node)
    {
        yield return node;
        foreach (var child in node.ChildArray)
        {
            foreach (var nested in Flatten(child))
            {
                yield return nested;
            }
        }
    }

    private static int VertexCount(DynamicGeometry geometry) => geometry.VertexFloats / ChunkMesher.FloatsPerVertex;

    private static float QuantizeHalf(float value) => (float)BitConverter.UInt16BitsToHalf(BitConverter.HalfToUInt16Bits((Half)value));

    private static List<SampleRow> Load(string fileName)
    {
        var path = Path.Combine(AppContext.BaseDirectory, "Repro", "Data", fileName);
        var rows = new List<SampleRow>();
        foreach (var line in File.ReadLines(path))
        {
            if (line.Length == 0 || line[0] == '#')
            {
                continue;
            }

            var fields = line.Split('\t');
            rows.Add(new SampleRow(
                fields[0],
                fields[1],
                int.Parse(fields[2], CultureInfo.InvariantCulture),
                int.Parse(fields[3], CultureInfo.InvariantCulture),
                int.Parse(fields[4], CultureInfo.InvariantCulture),
                new Vector3(
                    float.Parse(fields[5], CultureInfo.InvariantCulture),
                    float.Parse(fields[6], CultureInfo.InvariantCulture),
                    float.Parse(fields[7], CultureInfo.InvariantCulture)),
                float.Parse(fields[8], CultureInfo.InvariantCulture),
                float.Parse(fields[9], CultureInfo.InvariantCulture)));
        }

        return rows;
    }

    private readonly record struct SampleRow(
        string Layer,
        string Part,
        int Cube,
        int Polygon,
        int Vertex,
        Vector3 Position,
        float U,
        float V)
    {
        public (int Cube, int Polygon, int Vertex) Key => (Cube, Polygon, Vertex);
    }
}
